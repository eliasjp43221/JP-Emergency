    fun loadSeedServices(context: Context? = null): List<ServiceEntry> {
        if (context != null) {
            try {
                val jsonText = context.assets.open("jamalpur_services_v1.json")
                    .bufferedReader()
                    .use { it.readText() }
                val (parsed, result) = DataValidator.parseAndValidateJson(jsonText)
                if (result.isSuccess && parsed.isNotEmpty()) {
                    return parsed
                }
            } catch (_: Exception) {
                // অ্যাসেট ফাইল না পাওয়া গেলে (যেমন ইউনিট টেস্টে) কোড-ভিত্তিক যাচাইকৃত তালিকা ব্যবহার হবে
            }
        }
        return defaultSeedItems().map { it.toServiceEntry() }
    }

